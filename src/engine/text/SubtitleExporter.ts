import type { SubtitleLine, SubtitleStyle, TrackMetadata } from '../../types';

function formatAssTime(seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  const cs = Math.floor((seconds % 1) * 100);

  return `${h}:${m.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')}.${cs
    .toString()
    .padStart(2, '0')}`;
}

function formatSrtTime(seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  const ms = Math.floor((seconds % 1) * 1000);

  return `${h.toString().padStart(2, '0')}:${m.toString().padStart(2, '0')}:${s
    .toString()
    .padStart(2, '0')},${ms.toString().padStart(3, '0')}`;
}

export interface AssCanvasDimensions {
  width: number;
  height: number;
}

/**
 * Converts a CSS hex color (#RRGGBB or #RGB) to ASS v4.00+ &H00BBGGRR byte order.
 */
export function hexToAssBgr(hex: string | undefined, fallback = '&H00FFFFFF'): string {
  const cleaned = (hex || '').trim().replace(/^#/, '');
  if (/^[0-9a-fA-F]{6}$/.test(cleaned)) {
    const r = cleaned.slice(0, 2).toUpperCase();
    const g = cleaned.slice(2, 4).toUpperCase();
    const b = cleaned.slice(4, 6).toUpperCase();
    return `&H00${b}${g}${r}`;
  }
  if (/^[0-9a-fA-F]{3}$/.test(cleaned)) {
    const r = `${cleaned[0]}${cleaned[0]}`.toUpperCase();
    const g = `${cleaned[1]}${cleaned[1]}`.toUpperCase();
    const b = `${cleaned[2]}${cleaned[2]}`.toUpperCase();
    return `&H00${b}${g}${r}`;
  }
  return fallback;
}

/**
 * Generates standards-compliant Advanced SubStation Alpha v4.00+ (.ass) content.
 */
export function generateAss(
  lines: SubtitleLine[],
  style: SubtitleStyle,
  track?: TrackMetadata,
  dimensions: AssCanvasDimensions = { width: 1920, height: 1080 }
): string {
  const title = track?.title || 'SubStellar Project';
  const artist = track?.artist || 'Unknown Artist';
  const fontName = (style.fontFamily || 'Segoe UI').replace(/,/g, ' ');
  const transFontSize = Math.max(18, Math.round(style.fontSize * 0.55));
  const transMarginV = Math.max(16, style.yOffset - transFontSize - 10);
  const alignment =
    style.verticalPosition === 'top' ? 8 : style.verticalPosition === 'center' ? 5 : 2;

  const primaryColor = hexToAssBgr(style.fillColor, '&H00FFFFFF');
  const secondaryColor = hexToAssBgr(style.wordActiveColor || style.innerStrokeColor, '&H00FFB48F');
  const outlineColor = hexToAssBgr(style.outerStrokeColor, '&H001B1614');
  const rubyPrimaryColor = hexToAssBgr(style.rubyActiveColor, '&H00B5FF5A');
  const rubySecondaryColor = hexToAssBgr(style.rubyFillColor, '&H00FFB48F');
  const transColor = hexToAssBgr(style.translationFillColor, '&H00CAC3BF');

  return `[Script Info]
; Script generated by SubStellar Studio (https://github.com/SayMaven/sub-stellar)
; Title: ${title} - ${artist}
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: ${dimensions.width}
PlayResY: ${dimensions.height}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,${fontName},${style.fontSize},${primaryColor},${secondaryColor},${outlineColor},&H80000000,-1,0,0,0,100,100,0,0,1,${style.outerStrokeWidth},2,${alignment},40,40,${style.yOffset},1
Style: Furigana,${fontName},${Math.round(style.fontSize * style.rubyScale)},${rubyPrimaryColor},${rubySecondaryColor},${outlineColor},&H80000000,-1,0,0,0,100,100,0,0,1,${Math.max(2, Math.round(style.outerStrokeWidth * 0.5))},1,${alignment},40,40,${style.yOffset + Math.round(style.fontSize * 0.9)},1
Style: Translation,${fontName},${transFontSize},${transColor},${transColor},${outlineColor},&H80000000,0,0,0,0,100,100,0,0,1,4,1,${alignment},40,40,${transMarginV},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
${lines
  .map((line) => {
    const start = formatAssTime(line.startTime);
    const end = formatAssTime(line.endTime);

    let eventText = '';
    if (line.tokens && line.tokens.length > 0) {
      const hasSpaceInRaw = /\s/.test(line.text);
      line.tokens.forEach((token, i) => {
        const tokenDurationCs = Math.max(1, Math.round((token.endTime - token.startTime) * 100));
        const trailingSpace = hasSpaceInRaw && i < line.tokens.length - 1 ? ' ' : '';
        eventText += `{\\k${tokenDurationCs}}${token.text}${trailingSpace}`;
      });
    } else {
      eventText = line.text;
    }

    const mainDialogue = `Dialogue: 0,${start},${end},Default,,0,0,0,,${eventText}`;
    if (line.translation && line.translation.trim().length > 0) {
      return `${mainDialogue}\nDialogue: 0,${start},${end},Translation,,0,0,0,,${line.translation.trim()}`;
    }
    return mainDialogue;
  })
  .join('\n')}
`;
}

/**
 * Generates standard SubRip (.srt) content.
 */
export function generateSrt(lines: SubtitleLine[]): string {
  return lines
    .map((line, idx) => {
      const start = formatSrtTime(line.startTime);
      const end = formatSrtTime(line.endTime);
      const cleanText = line.text.replace(/\{([^|]+)\|[^}]+\}/g, '$1');
      const transLine =
        line.translation && line.translation.trim().length > 0
          ? `\n${line.translation.trim()}`
          : '';

      return `${idx + 1}\n${start} --> ${end}\n${cleanText}${transLine}\n`;
    })
    .join('\n');
}

/**
 * Triggers a browser file download of the given text content.
 */
export function downloadFile(filename: string, content: string, mimeType: string): void {
  if (typeof document === 'undefined') return;

  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
